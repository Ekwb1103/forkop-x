import { defineConfig } from 'tsup';
import fs from 'fs';
import path from 'path';
import { compactLuCIAssets } from './scripts/compact-luci-assets';
import { readTranslations } from './scripts/read-translations';

export default defineConfig({
    entry: ['src/main.ts'],
    format: ['esm'], // пусть tsup генерит export {...}
    outDir: '../luci-app-forkop/htdocs/luci-static/resources/view/forkop',
    outExtension: () => ({ js: '.js' }),
    dts: false,
    clean: false,
    sourcemap: false,
    banner: {
        js: `// This file is autogenerated, please don't change manually \n"use strict";`,
    },
    esbuildOptions(options) {
        options.inject = [path.resolve('src/helpers/forkopLanguage.ts')];
        options.define = {
            ...options.define,
            __FORKOP_RUSSIAN__: JSON.stringify(JSON.stringify(readTranslations(fs.readFileSync('../luci-app-forkop/po/ru/forkop.po', 'utf8')))),
        };
        options.legalComments = 'none';
        // Emit non-ASCII text as UTF-8 instead of \uXXXX escapes (the Russian
        // dictionary is ~3x smaller); LuCI already loads UTF-8 view sources.
        options.charset = 'utf8';
        // Preserve LuCI directives and exported names; only compact whitespace.
        options.minifyWhitespace = true;
        options.minifyIdentifiers = false;
        options.minifySyntax = false;
    },
    onSuccess: () => {
        const outDir =
            '../luci-app-forkop/htdocs/luci-static/resources/view/forkop';
        const file = path.join(outDir, 'main.js');
        let code = fs.readFileSync(file, 'utf8');

        code = code.replace(
            /export\s*{([\s\S]*?)}/,
            (match, group) => {
                return `return baseclass.extend({${group}})`;
            }
        );

        fs.writeFileSync(file, code, 'utf8');
        console.log(`✅ Patched LuCI build: ${file}`);
        compactLuCIAssets();
    },
});
